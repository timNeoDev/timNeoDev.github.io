def _normalize(text: str) -> str:
    return text.lower().replace("ё", "е")


def _has(key: str, q: str) -> bool:
    """Ключ ищется с начала слова: иначе «пока» находится в «покажи», а «айс» — в «прайс»."""
    return re.search(r"\b" + _normalize(key), q) is not None


def answer(question: str) -> tuple[str, bool]:
    """Подбирает ответ на вопрос. Возвращает (текст, нужна_ли_кнопка_брони)."""
    q = _normalize(question)

    # Названия позиций меню — самый точный сигнал
    items = [text for keys, text in ITEMS if any(_has(k, q) for k in keys)]

    # Общие темы отвечают, только если не нашлось ничего конкретнее
    generic = {"menu", "hello", "thanks"}
    scores = []
    for name, keys, replies in INTENTS:
        score = sum(1 for k in keys if _has(k, q))
        if score:
            scores.append((score, name, replies))
    if _has("не крепк", q):  # «не крепкое» не должно запускать совет «покрепче»
        scores = [s for s in scores if s[1] != "strong"]
    scores.sort(key=lambda s: -s[0])
    specific = [s for s in scores if s[1] not in generic]
    if specific or items:
        scores = specific
    chosen = scores[:1] + [s for s in scores[1:2] if s[0] == scores[0][0]]  # вторая тема — только равная по весу

    parts: list[str] = list(items[:3])
    wants_booking = False
    for _, name, replies in chosen:
        parts.append(random.choice(replies))
        wants_booking |= name == "booking"

    if not parts:
        parts.append(random.choice(FALLBACK))
    return " ".join(parts), wants_booking


async def stream(text: str, on_update: Callable[[str], Awaitable[None]]) -> None:
    """Выдаёт текст по словам с паузами — как потоковый ответ нейросети."""
    await asyncio.sleep(random.uniform(0.6, 1.2))  # «думает»
    words = re.findall(r"\S+\s*", text)
    shown = ""
    for i in range(0, len(words), 3):
        shown += "".join(words[i:i + 3])
        await on_update(shown)
        await asyncio.sleep(random.uniform(0.12, 0.25))
