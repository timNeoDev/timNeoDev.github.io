"""Проверка ответов демо-режима. Запуск: python test_demo.py"""
import demo

# вопрос -> кусок текста, который должен быть в ответе (None — общий ответ «не знаю»)
CASES = {
    "покажи меню": "советую наш хит",
    "есть прайс?": None,  # раньше «прайс» находил «айс»-латте
    "хочу что-нибудь не крепкое": "не любите горечь",
    "во сколько последний заказ?": "08:00 до 22:00",  # раньше «последний» находил «лёд»
    "можно у вас делать фотографии?": None,  # раньше «фотографии» находил «раф»
    "сколько стоит капучино и круассан?": "Круассан — 190",
    "а можно безлактозное?": "овсяном",
    "хочу забронировать столик": "кнопкой ниже",
    "до скольки работаете?": "08:00 до 22:00",
    "есть wifi?": "Wi-Fi",
    "пока!": "До встречи",
    "какая погода завтра?": None,
}

failed = 0
for question, expected in CASES.items():
    text, _ = demo.answer(question)
    ok = text in demo.FALLBACK if expected is None else expected in text
    if not ok:
        failed += 1
        print(f"FAIL: {question!r} -> {text!r}")

assert "бодрости" not in demo.answer("хочу что-нибудь не крепкое")[0]
assert demo.answer("хочу забронировать столик")[1] is True
print(f"{len(CASES) - failed}/{len(CASES)} OK")
assert failed == 0
